package session_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/curbol/unity-sync/internal/session"
)

// Payloads are inlined rather than kept as testdata files: the repo's .gitignore matches
// *.curl and cookies.txt at any depth, so file fixtures would be silently uncommitted
// and CI would fail on missing testdata.
const curlPaste = `curl 'https://assetstore.unity.com/api/graphql/batch' \
  -H 'accept: application/json' \
  -H 'Cookie: _csrf=stale; LS=the-credential; DS=abc; activeOrgId=123' \
  --data-raw '[]'`

// A real export marks HttpOnly rows with a #HttpOnly_ prefix on the record itself.
const cookiesTxt = "# Netscape HTTP Cookie File\n" +
	"# This file was generated by a browser extension\n" +
	"#HttpOnly_.unity.com\tTRUE\t/\tTRUE\t0\tLS\tthe-credential\n" +
	"assetstore.unity.com\tFALSE\t/\tTRUE\t0\tDS\tabc\n" +
	"example.com\tFALSE\t/\tFALSE\t0\tunrelated\tnope\n"

func write(t *testing.T, name, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestResolveReadsAPastedCurlCommand(t *testing.T) {
	got, _, err := session.ResolveFrom(write(t, "session.curl", curlPaste))
	if err != nil {
		t.Fatalf("Resolve: %v", err)
	}
	if !strings.Contains(got, "LS=the-credential") {
		t.Errorf("header %q lost the credential", got)
	}
	if !strings.Contains(got, "DS=abc") {
		t.Errorf("header %q dropped an ordinary cookie", got)
	}
}

// An export whose header comment mentions curl must still parse as a cookies.txt.
func TestCurlDetectionUsesStructureNotTheWord(t *testing.T) {
	body := "# Generated for use with curl\n" +
		"#HttpOnly_.unity.com\tTRUE\t/\tTRUE\t0\tLS\tthe-credential\n"
	if _, _, err := session.ResolveFrom(write(t, "cookies.txt", body)); err != nil {
		t.Fatalf("Resolve: %v", err)
	}
}

func TestHeaderIsDeterministic(t *testing.T) {
	p := write(t, "session.curl", curlPaste)
	first, _, err := session.ResolveFrom(p)
	if err != nil {
		t.Fatal(err)
	}
	for range 5 {
		again, _, err := session.ResolveFrom(p)
		if err != nil {
			t.Fatal(err)
		}
		if again != first {
			t.Fatalf("header varies between reads:\n%q\n%q", first, again)
		}
	}
}

func TestDiscoverPrefersSessionCurl(t *testing.T) {
	dir := t.TempDir()
	if _, ok := session.Discover(dir); ok {
		t.Fatal("Discover found a session in an empty dir")
	}
	if err := os.WriteFile(filepath.Join(dir, "cookies.txt"), []byte("x"), 0o600); err != nil {
		t.Fatal(err)
	}
	got, ok := session.Discover(dir)
	if !ok || filepath.Base(got) != "cookies.txt" {
		t.Fatalf("Discover = %q, %v; want the cookies.txt", got, ok)
	}
	if err := os.WriteFile(filepath.Join(dir, "session.curl"), []byte("x"), 0o600); err != nil {
		t.Fatal(err)
	}
	got, _ = session.Discover(dir)
	if filepath.Base(got) != "session.curl" {
		t.Errorf("Discover = %q, want session.curl to win", got)
	}
}
